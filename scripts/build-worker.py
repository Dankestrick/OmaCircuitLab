#!/usr/bin/env python3
"""Write the WorkerScript modules from the .js libraries.

qml/lib/*.js stays the source of truth for the QML UI and the Node tests.
Quickshell's WorkerScript ignores `.import` in a plain script and runs an
`.mjs` file as an ES module, so Run loads qml/lib/worker/EngineWorker.mjs.

Mcu.js is left out. Lesson 1 does not need the interpreter.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
LIB = ROOT / "qml" / "lib"
OUT = LIB / "worker"
SOURCES = ("Catalog.js", "Engine.js", "EngineWorker.js")

IMPORT_RE = re.compile(r'^\.import "([A-Za-z0-9_]+)\.js" as ([A-Za-z0-9_]+)\s*$')
DECL_RE = re.compile(r"^(?:function |var )")


def transform(name, text):
    out = ["// Generated by scripts/build-worker.py from %s. Do not edit.\n" % name]
    for line in text.splitlines():
        if line.strip() == ".pragma library":
            continue
        match = IMPORT_RE.match(line)
        if match:
            module, alias = match.group(1), match.group(2)
            out.append('import * as %s from "./%s.mjs"\n' % (alias, module))
            continue
        if DECL_RE.match(line):
            out.append("export " + line + "\n")
            continue
        out.append(line + "\n")
    return "".join(out)


def main():
    missing = [name for name in SOURCES if not (LIB / name).is_file()]
    if missing:
        sys.stderr.write("missing %s\n" % ", ".join(missing))
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    for name in SOURCES:
        dest = OUT / (name[:-3] + ".mjs")
        dest.write_text(transform(name, (LIB / name).read_text(encoding="utf-8")), encoding="utf-8")
        print("wrote %s" % dest.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
