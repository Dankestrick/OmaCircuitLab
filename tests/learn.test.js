const load = require("./load"), assert = require("assert")
const L = load("Learn.js")
const near = (a, b, tol) => assert(Math.abs(a - b) <= (tol || 1e-9) * Math.max(1, Math.abs(b)), a + " != " + b)
near(L.ohm(9, null, 450).i, 0.02)
near(L.ohm(null, 0.02, 220).v, 4.4)
near(L.ohm(5, 0.01, null).r, 500)
const led = L.ledResistor(9, "red", 15)
assert(led.ok); near(led.exact, 480); assert.strictEqual(led.pick, 560)
assert(!L.ledResistor(2.5, "blue", 15).ok)
near(L.divider(9, 10000, 10000).vout, 4.5)
near(L.parallel([100, 100]), 50); near(L.series([100, 220]), 320)
near(L.fromBands(4, 7, 2), 4700)
assert.strictEqual(JSON.stringify(L.bandsFor(4700)), "[4,7,2]")
assert.strictEqual(JSON.stringify(L.bandsFor(220)), "[2,2,1]")
near(L.parseSI("4.7k"), 4700); near(L.parseSI("20m"), 0.02); near(L.parseSI("100u"), 1e-4); near(L.parseSI("1M"), 1e6); near(L.parseSI("220Ω"), 220)
assert.strictEqual(L.parseSI("abc"), null)
console.log("learn ok")
